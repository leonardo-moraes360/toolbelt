// Bootstrap (docs/specs/egm-drift-bootstrap.md, B2): a new gated document
// whose skeleton has every section its standard requires and a Sources
// section of relative links to the --from files, which the R7 collection
// must include exactly. tb never overwrites, stages or commits it, and reads
// no file content.

// BootstrapStatus is the generated status line.
const BootstrapStatus = "Status: **draft, generated by tb egm bootstrap** (not reviewed)."

// BootstrapOptions are tb egm bootstrap's inputs.
type BootstrapOptions struct {
	Cwd        string // absolute
	Target     string
	From       []string
	ConfigFile string
}

// BootstrapResult reports what was written and what was skipped.
type BootstrapResult struct {
	Doc      string          `json:"doc"`
	Type     string          `json:"type"`
	Sources  []string        `json:"sources"`
	Skipped  []SkippedSource `json:"skipped"`
	Next     string          `json:"next"`
	Warnings []Warning       `json:"warnings,omitempty"`
}

// Bootstrap writes the skeleton of a new gated document.
func Bootstrap(ctx context.Context, o *BootstrapOptions) (*BootstrapResult, error) {
	repo, err := DiscoverRepo(filepath.Join(o.Cwd, ".egm-bootstrap"))
	if err != nil {
		return nil, err
	}
	user, err := LoadUserConfig(o.ConfigFile)
	if err != nil {
		return nil, errorf(ExitError, "config", "%v", err)
	}
	raw, _ := readRepoConfig(repo.Root)
	set := ApplyRepoConfig(&user, raw)
	cwd, err := filepath.EvalSymlinks(o.Cwd)
	if err != nil {
		return nil, errorf(ExitError, "usage", "%s: %v", o.Cwd, err)
	}
	rel, err := bootstrapTarget(repo.Root, cwd, o.Target, &set)
	if err != nil {
		return nil, err
	}
	if len(o.From) == 0 {
		return nil, errorf(ExitError, "usage", "--from is required (files or directories inside the repository)")
	}
	files, skipped, err := bootstrapFiles(ctx, repo, cwd, rel, o.From, &set)
	if err != nil {
		return nil, err
	}
	if len(files) == 0 {
		return nil, errorf(ExitError, "bootstrap_sources", "no --from file can be a source of %s (%d skipped)", rel, len(skipped))
	}
	docType := DocType(rel, set.DocTypes)
	text := skeleton(rel, docType, files)
	if err := checkBootstrapSources(ctx, repo, &set, rel, text, files); err != nil {
		return nil, err
	}
	if err := createNew(repo.Root, rel, text); err != nil {
		return nil, err
	}
	return &BootstrapResult{Doc: rel, Type: docType, Sources: files, Skipped: skipped, Warnings: set.Warnings,
		Next: "edit " + rel + ", then run: tb egm review " + rel}, nil
}

// bootstrapTarget: inside the repository, gated, absent, in an existing
// real directory reached through no symlink.
func bootstrapTarget(root, cwd, target string, set *Settings) (string, error) {
	rel, err := gateRel(root, cwd, target)
	if err != nil {
		return "", err
	}
	if !IsGated(set.DocGlobs, rel) {
		return "", errorf(ExitError, "usage", "%s is not a gated document path (egm.doc_globs)", rel)
	}
	if dir := path.Dir(rel); dir != "." {
		fi, reason, missing := lstatChain(root, dir)
		switch {
		case missing:
			return "", errorf(ExitError, "usage", "directory %s does not exist", dir)
		case reason != "":
			return "", errorf(ExitError, "bootstrap_path", "%s: a path component is a %s", dir, reason)
		case !fi.IsDir():
			return "", errorf(ExitError, "bootstrap_path", "%s is not a directory", dir)
		}
	}
	if _, err := os.Lstat(filepath.Join(root, filepath.FromSlash(rel))); !errors.Is(err, os.ErrNotExist) {
		return "", errorf(ExitError, "bootstrap_exists", "%s already exists; bootstrap never overwrites", rel)
	}
	return rel, nil
}

// bootstrapFiles expands --from (directories to their tracked files) and
// keeps the files that pass the Phase A path rules; the rest are skipped
// with a reason.
func bootstrapFiles(ctx context.Context, repo *Repo, cwd, doc string, from []string, set *Settings) (files []string, skipped []SkippedSource, err error) {
	var cands []string
	for _, f := range from {
		rel, err := gateRel(repo.Root, cwd, f)
		if err != nil {
			return nil, nil, err
		}
		fi, reason, missing := lstatChain(repo.Root, rel)
		switch {
		case missing:
			return nil, nil, errorf(ExitError, "usage", "--from %s does not exist", rel)
		case reason != "":
			skipped = append(skipped, SkippedSource{Path: rel, Reason: reason})
			continue
		case fi.IsDir():
			entries, err := repo.LsFilesStage(ctx, rel)
			if err != nil {
				return nil, nil, err
			}
			for _, e := range entries {
				cands = appendNew(cands, []string{e.Path})
			}
		default:
			cands = appendNew(cands, []string{rel})
		}
	}
	sort.Strings(cands)
	files, more, err := acceptSources(ctx, repo, doc, cands, set)
	return files, append(skipped, more...), err
}

// acceptSources keeps tracked regular files reached through no symlink and
// not denied.
func acceptSources(ctx context.Context, repo *Repo, doc string, cands []string, set *Settings) (files []string, skipped []SkippedSource, err error) {
	var look []string
	for _, f := range cands {
		if denied(f, doc, set.DocGlobs) {
			skipped = append(skipped, SkippedSource{Path: f, Reason: "excluded"})
			continue
		}
		fi, reason, missing := lstatChain(repo.Root, f)
		switch {
		case missing:
			skipped = append(skipped, SkippedSource{Path: f, Reason: "missing"})
		case reason != "":
			skipped = append(skipped, SkippedSource{Path: f, Reason: reason})
		case !fi.Mode().IsRegular():
			skipped = append(skipped, SkippedSource{Path: f, Reason: "not_regular"})
		default:
			look = append(look, f)
		}
	}
	if len(look) == 0 {
		return nil, skipped, nil
	}
	entries, err := repo.LsFilesStage(ctx, look...)
	if err != nil {
		return nil, nil, err
	}
	tracked := map[string]bool{}
	for _, e := range entries {
		tracked[e.Path] = regularMode(e.Mode)
	}
	for _, f := range look {
		if tracked[f] {
			files = append(files, f)
		} else {
			skipped = append(skipped, SkippedSource{Path: f, Reason: "untracked"})
		}
	}
	return files, skipped, nil
}

// skeleton is the document: title, generated status, the standard's
// required sections with TODO, and Sources as links relative to the doc.
func skeleton(rel, docType string, files []string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\n%s\n\n", titleFrom(rel), BootstrapStatus)
	for _, pair := range requiredHeadings[structuralStandard(docType)] {
		fmt.Fprintf(&b, "%s\n\nTODO\n\n", pair[0])
	}
	b.WriteString("## Sources\n\n")
	dir := path.Dir(rel)
	for _, f := range files {
		link, err := filepath.Rel(filepath.FromSlash(dir), filepath.FromSlash(f))
		if err != nil {
			link = f
		}
		fmt.Fprintf(&b, "- [%s](%s)\n", f, filepath.ToSlash(link))
	}
	return b.String()
}

// titleFrom turns docs/specs/router-bus.md into "Router bus"; an ADR's
// numeric prefix stays ("020 x" -> "020 x").
func titleFrom(rel string) string {
	base := strings.TrimSuffix(path.Base(rel), path.Ext(rel))
	words := strings.FieldsFunc(base, func(r rune) bool { return r == '-' || r == '_' || r == ' ' })
	t := strings.Join(words, " ")
	if t == "" {
		return "Untitled"
	}
	r := []rune(t)
	r[0] = unicode.ToUpper(r[0])
	return string(r)
}

// checkBootstrapSources refuses a skeleton whose R7 sources are not
// exactly the accepted files (one dropped as secret-like or by a limit):
// its first review would start with an excluded source.
func checkBootstrapSources(ctx context.Context, repo *Repo, set *Settings, rel, text string, files []string) error {
	got, err := CollectSources(ctx, repo, set, rel, text)
	if err != nil {
		return err
	}
	included := map[string]bool{}
	for _, s := range got.Included {
		included[s.Path] = true
	}
	var dropped []string
	for _, f := range files {
		if included[f] {
			continue
		}
		reason := "not included"
		for _, s := range got.Skipped {
			if s.Path == f {
				reason = s.Reason
			}
		}
		dropped = append(dropped, f+" ("+reason+")")
	}
	if len(dropped) > 0 || len(got.Included) != len(files) {
		return errorf(ExitError, "bootstrap_sources", "the review would not include every --from file as a source: %s", strings.Join(dropped, ", "))
	}
	return nil
}

// createNew writes rel under root with O_EXCL and no final symlink; the
// parent was checked component by component.
func createNew(root, rel, text string) error {
	r, err := os.OpenRoot(root)
	if err != nil {
		return err
	}
	defer r.Close()
	name := filepath.FromSlash(rel)
	f, err := r.OpenFile(name, os.O_WRONLY|os.O_CREATE|os.O_EXCL|oNoFollow, 0o644)
	if errors.Is(err, os.ErrExist) {
		return errorf(ExitError, "bootstrap_exists", "%s already exists; bootstrap never overwrites", rel)
	}
	if err != nil {
		return err
	}
	_, werr := f.WriteString(text)
	cerr := f.Close()
	if werr != nil || cerr != nil {
		_ = r.Remove(name)
		return errors.Join(werr, cerr)
	}
	return nil
}
