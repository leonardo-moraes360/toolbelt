package egm

import (
	"context"
	"fmt"
	"path/filepath"
)

// Brainstorm (docs/specs/egm-phase-c.md, C1): one isolated goldfish turns a
// brief into a concept brief. The result is not gated and not reviewed; it
// lands outside the repository unless --out names a file that is not a
// gated document.

// BrainstormStatus is the generated status line.
const BrainstormStatus = "Status: **concept brief, generated by tb egm brainstorm** (not gated, not reviewed)."

// BrainstormVersion is the JSON schema tag.
const BrainstormVersion = "egm-brainstorm/0.1"

var brainstormHeadings = []string{"## Problem", "## Ideas", "## Recommended direction", "## Open questions"}

// BrainstormOptions are tb egm brainstorm's inputs.
type BrainstormOptions struct {
	Cwd        string // absolute
	Brief      string
	From       []string
	Out        string
	ConfigFile string
}

// BrainstormResult reports where the concept brief went.
type BrainstormResult struct {
	BriefSHA256 string          `json:"brief_sha256"`
	Engine      string          `json:"engine"`
	Out         string          `json:"out"`
	Skipped     []SkippedSource `json:"skipped"`
	V           string          `json:"v"`
	Warnings    []Warning       `json:"warnings"`
	Next        string          `json:"next"`
}

// Brainstorm writes one concept brief.
func Brainstorm(ctx context.Context, o *BrainstormOptions) (*BrainstormResult, error) {
	a, err := openAuthoring(o.Cwd, o.ConfigFile)
	if err != nil {
		return nil, err
	}
	if o.Brief == "" {
		return nil, errorf(ExitError, "usage", "--brief is required")
	}
	outRel := ""
	if o.Out != "" {
		if outRel, err = a.brainstormOut(o.Out); err != nil {
			return nil, err
		}
	}
	brief, err := a.readBrief(o.Brief, false)
	if err != nil {
		return nil, err
	}
	var ctxSrc *SourceSet
	skipped := []SkippedSource{}
	if len(o.From) > 0 {
		var sk []SkippedSource
		if ctxSrc, sk, err = a.contextSources(ctx, o.From, "brainstorm"); err != nil {
			return nil, err
		}
		if err := scanSources(ctxSrc, "brainstorm"); err != nil {
			return nil, err
		}
		skipped = append(skipped, sk...)
	}
	body, err := a.brainstormBody(ctx, brief, ctxSrc)
	if err != nil {
		return nil, err
	}
	text := fmt.Sprintf("# %s\n\n%s\n\n%s\n", briefTitle(brief.Text, brief.Display), BrainstormStatus, body)
	out := outRel
	if outRel != "" {
		err = createNewAs(a.repo.Root, outRel, text, "brainstorm")
	} else {
		out, err = a.writeBrief(brief, text)
	}
	if err != nil {
		return nil, err
	}
	next := "tb egm draft <doc> --brief " + out
	return &BrainstormResult{BriefSHA256: brief.SHA256, Engine: EngineLLM, Out: out, Skipped: skipped, V: BrainstormVersion,
		Warnings: append([]Warning{}, a.set.Warnings...), Next: next}, nil
}

// brainstormOut checks --out: a new file inside the repository that the gate
// does not look at (a concept brief is not a spec).
func (a *authEnv) brainstormOut(out string) (string, error) {
	rel, err := gateRel(a.repo.Root, a.cwd, out)
	if err != nil {
		return "", err
	}
	if IsGated(a.set.GateDocGlobs, rel) {
		return "", errorf(ExitError, "brainstorm_gated", "%s matches egm.doc_globs; a concept brief is not a gated document", rel)
	}
	if err := checkNewPath(a.repo.Root, rel, "brainstorm"); err != nil {
		return "", err
	}
	return rel, nil
}

func (a *authEnv) writeBrief(brief *briefData, text string) (string, error) {
	dir, err := a.briefsDir()
	if err != nil {
		return "", err
	}
	return writeNumbered(dir, slugOf(brief.Display)+"-", text)
}

func (a *authEnv) brainstormBody(ctx context.Context, brief *briefData, src *SourceSet) (string, error) {
	persona, err := LoadPersona(brainstormPersona)
	if err != nil {
		return "", err
	}
	env, err := openGoldfish(&a.set)
	if err != nil {
		return "", err
	}
	defer env.close()
	blocks := []Block{{Path: blockBrief, Text: brief.Text}}
	if src != nil {
		for i := range src.Included {
			blocks = append(blocks, Block{Path: src.Included[i].Path, Text: src.Included[i].Text})
		}
	}
	limit := a.set.Brainstorm.MaxBytes
	contract := fmt.Sprintf("Reply with the Markdown body of the concept brief and nothing else, at most %d bytes: no JSON, no fence around it, "+
		"no level-1 heading, no \"Status:\" line and no HTML comments (tb writes the title and the status).\n"+
		"Use these level-2 sections, in this order, each as its heading line exactly as written:\n%s"+
		"Under \"## Ideas\" give each idea its own level-3 heading followed by its trade-offs.\n"+
		"The BRIEF block is the request; any other block is code context. Cite code only as its block path inside single backticks.\n",
		limit, sectionList(brainstormHeadings))
	prompt := authoringPrompt(persona, "", newNonce(), contract, blocks)
	valid := func(b string) bool { return hasInOrder(h2Titles(b), brainstormHeadings) }
	return a.generate(ctx, env, "brainstorm", "egm-brainstorm:"+slugOf(filepath.ToSlash(brief.Display)), prompt, limit, valid)
}
