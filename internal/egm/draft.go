// Draft (docs/specs/egm-phase-c.md, C2 and C3): the first version of a spec
// or ADR, from an elephant-written body (--body) or one isolated goldfish
// (--engine llm). tb assembles and checks it; it writes no review state, so
// the draft reaches PASS only through the normal review loop. With --update
// tb never edits the document: it writes a proposal outside the tree.

// DraftStatus is the generated status line.
const DraftStatus = "Status: **draft, generated by tb egm draft** (not reviewed)."

// DraftVersion is the JSON schema tag.
const DraftVersion = "egm-draft/0.1"

// DraftOptions are tb egm draft's inputs.
type DraftOptions struct {
	Cwd        string // absolute
	Target     string
	Brief      string
	From       []string
	BodyFile   string // --body: deterministic
	Engine     string // llm, or empty with BodyFile
	Update     bool
	ConfigFile string
}

// DraftResult reports what was written.
type DraftResult struct {
	Doc      string          `json:"doc,omitempty"`
	Proposal string          `json:"proposal,omitempty"`
	Diff     string          `json:"diff,omitempty"`
	Engine   string          `json:"engine"`
	Skipped  []SkippedSource `json:"skipped"`
	Sources  []string        `json:"sources"`
	V        string          `json:"v"`
	Warnings []Warning       `json:"warnings"`
	Next     string          `json:"next"`
}

type draftRun struct {
	*authEnv
	o       *DraftOptions
	brief   *briefData
	llm     bool
	rel     string
	docType string
}

// Draft writes a new document, or with Update a proposal for an existing one.
func Draft(ctx context.Context, o *DraftOptions) (*DraftResult, error) {
	llm := o.Engine == EngineLLM
	switch {
	case o.Engine != "" && !llm:
		return nil, errorf(ExitError, "usage", "--engine must be llm (use --body for the deterministic path), got %q", o.Engine)
	case llm == (o.BodyFile != ""):
		return nil, errorf(ExitError, "usage", "give exactly one of --body <file> and --engine llm")
	case llm && o.Brief == "":
		return nil, errorf(ExitError, "usage", "--engine llm needs --brief")
	case o.Update && len(o.From) > 0:
		return nil, errorf(ExitError, "usage", "--update keeps the document's own sources; --from is for new documents")
	}
	a, err := openAuthoring(o.Cwd, o.ConfigFile)
	if err != nil {
		return nil, err
	}
	d := &draftRun{authEnv: a, o: o, llm: llm}
	if o.Brief != "" {
		if d.brief, err = a.readBrief(o.Brief, true); err != nil {
			return nil, err
		}
	}
	if o.Update {
		return d.update(ctx)
	}
	return d.create(ctx)
}

func (d *draftRun) engine() string {
	if d.llm {
		return EngineLLM
	}
	return EngineDeterministic
}

func (d *draftRun) create(ctx context.Context) (*DraftResult, error) {
	rel, err := newGatedTarget(d.repo.Root, d.cwd, d.o.Target, &d.set, "draft")
	if err != nil {
		return nil, err
	}
	d.rel, d.docType = rel, DocType(rel, d.set.DocTypes)
	var files []string
	skipped := []SkippedSource{}
	var got *SourceSet
	if len(d.o.From) > 0 {
		var sk []SkippedSource
		if files, sk, err = bootstrapFiles(ctx, d.repo, d.cwd, rel, d.o.From, &d.set); err != nil {
			return nil, err
		}
		skipped = append(skipped, sk...)
		if len(files) == 0 {
			return nil, errorf(ExitError, "draft_sources", "no --from file can be a source of %s: %s", rel, skippedList(skipped))
		}
		probe := headWith(rel, DraftStatus) + sourcesSection(rel, files)
		if got, err = checkSourcesAs(ctx, d.repo, &d.set, rel, probe, files, "draft_sources"); err != nil {
			return nil, err
		}
		if err := scanSources(got, "draft"); err != nil && d.llm {
			return nil, err
		}
	}
	body, err := d.body(ctx, got, "")
	if err != nil {
		return nil, err
	}
	text := headWith(rel, DraftStatus) + withRequiredSections(body, d.docType)
	if len(files) > 0 {
		text += "\n\n" + sourcesSection(rel, files)
	}
	text = strings.TrimRight(text, "\n") + "\n"
	final, err := CollectSources(ctx, d.repo, &d.set, rel, text)
	if err != nil {
		return nil, err
	}
	if err := exactSources(final, files, nil); err != nil {
		return nil, err
	}
	if err := createNewAs(d.repo.Root, rel, text, "draft"); err != nil {
		return nil, err
	}
	return &DraftResult{Doc: rel, Engine: d.engine(), Skipped: skipped, Sources: nonNil(files), V: DraftVersion,
		Warnings: append(append([]Warning{}, d.set.Warnings...), final.Warnings...), Next: draftNext(d.repo.Root, rel)}, nil
}

// loadExisting checks the document --update revises and returns its text.
func (d *draftRun) loadExisting() (string, error) {
	rel, err := gateRel(d.repo.Root, d.cwd, d.o.Target)
	if err != nil {
		return "", err
	}
	if !IsGated(d.set.GateDocGlobs, rel) {
		return "", errorf(ExitError, "usage", "%s is not a gated document path (egm.doc_globs plus the repository's extra gated globs)", rel)
	}
	if inDenied(rel) {
		return "", errorf(ExitError, "draft_path", "%s is under .git or a path R7 denies", rel)
	}
	fi, reason, missing := lstatChain(d.repo.Root, rel)
	switch {
	case missing:
		return "", errorf(ExitError, "usage", "%s does not exist; --update revises an existing document", rel)
	case reason != "":
		return "", errorf(ExitError, "draft_path", "%s: a path component is a %s", rel, reason)
	case !fi.Mode().IsRegular():
		return "", errorf(ExitError, "draft_path", "%s is not a regular file", rel)
	}
	raw, err := readRegular(filepath.Join(d.repo.Root, filepath.FromSlash(rel)), d.set.MaxPacketBytes)
	if err != nil {
		return "", errorf(ExitError, "draft_path", "%s: %v", rel, err)
	}
	d.rel, d.docType = rel, DocType(rel, d.set.DocTypes)
	return string(raw), nil
}

func (d *draftRun) update(ctx context.Context) (*DraftResult, error) {
	existing, err := d.loadExisting()
	if err != nil {
		return nil, err
	}
	rel := d.rel
	cur, err := CollectSources(ctx, d.repo, &d.set, rel, existing)
	if err != nil {
		return nil, err
	}
	var want []string
	for i := range cur.Included {
		want = append(want, cur.Included[i].Path)
	}
	if d.llm {
		if err := d.vetExisting(existing, cur); err != nil {
			return nil, err
		}
	}
	red, _ := Redact(existing)
	body, err := d.body(ctx, cur, red)
	if err != nil {
		return nil, err
	}
	head, sources := splitDoc(existing)
	text := head + withRequiredSections(body, d.docType)
	if sources != "" {
		text += "\n\n" + sources
	}
	text = strings.TrimRight(text, "\n") + "\n"
	final, err := CollectSources(ctx, d.repo, &d.set, rel, text)
	if err != nil {
		return nil, err
	}
	if err := exactSources(final, want, cur); err != nil {
		return nil, err
	}
	diff, err := unifiedDiff(ctx, existing, text)
	if err != nil {
		return nil, err
	}
	dir, err := StateDir(d.repo.ID, Slug(rel))
	if err != nil {
		return nil, err
	}
	proposal, err := writeNumbered(filepath.Join(dir, "drafts"), "draft-", text)
	if err != nil {
		return nil, err
	}
	next := "apply the proposal to " + rel + " yourself (tb never edits it), then run: tb egm review " + rel +
		" (tb egm loop next " + rel + " when it already has a review state)"
	return &DraftResult{Proposal: proposal, Diff: diff, Engine: d.engine(), Skipped: []SkippedSource{}, Sources: nonNil(want), V: DraftVersion,
		Warnings: append(append([]Warning{}, d.set.Warnings...), final.Warnings...), Next: next}, nil
}

// vetExisting keeps a document that reads as an instruction, or holds a
// secret-like value, away from the goldfish.
func (d *draftRun) vetExisting(text string, cur *SourceSet) error {
	if _, secret := Redact(text); secret {
		return errorf(ExitError, "draft_secret", "%s has a secret-like value; it is not sent to a model", d.rel)
	}
	if fs := ScanInjection(ParseDoc(text, nil), d.rel); len(fs) > 0 {
		return errorf(ExitError, "draft_injection", "%s %s", d.rel, strings.TrimPrefix(fs[0].Message, "text "))
	}
	return scanSources(cur, "draft")
}

// body is the cleaned, scanned body from the file or the goldfish. src holds
// the code the goldfish may describe; existing is the document being revised.
func (d *draftRun) body(ctx context.Context, src *SourceSet, existing string) (string, error) {
	if !d.llm {
		return d.fileBody()
	}
	persona, err := LoadPersona(draftPersona)
	if err != nil {
		return "", err
	}
	standardName := structuralStandard(d.docType)
	standard, err := LoadStandard(standardName)
	if err != nil {
		return "", err
	}
	env, err := openGoldfish(&d.set)
	if err != nil {
		return "", err
	}
	defer env.close()
	blocks := []Block{{Path: blockBrief, Text: d.brief.Text}}
	if existing != "" {
		blocks = append(blocks, Block{Path: blockDocument, Text: existing})
	}
	if src != nil {
		for i := range src.Included {
			blocks = append(blocks, Block{Path: src.Included[i].Path, Text: src.Included[i].Text})
		}
	}
	var heads []string
	for _, h := range requiredHeadings[standardName] {
		heads = append(heads, h[0])
	}
	task := "Write the document body from the BRIEF block."
	if existing != "" {
		task = "Write the complete new version of the document in the DOCUMENT block, changed as the BRIEF block asks and otherwise as it is."
	}
	limit := d.set.Draft.MaxBytes
	contract := fmt.Sprintf("%s Reply with the Markdown body and nothing else, at most %d bytes: no JSON, no fence around it, "+
		"no level-1 heading, no \"Status:\" line, no \"## Sources\" section and no HTML comments (tb writes the title, the status and the sources).\n"+
		"Use these sections, in this order, each as its heading line exactly as written:\n%s"+
		"Cite a file only as its code data block path inside single backticks; cite no other file, path or URL, and never the BRIEF or DOCUMENT blocks.\n",
		task, limit, sectionList(heads))
	prompt := authoringPrompt(persona, standard, newNonce(), contract, blocks)
	return d.generate(ctx, env, "draft", "egm-draft:"+Slug(d.rel), prompt, limit, nil)
}

// fileBody reads --body (any file the user names) and cleans it like the
// goldfish output.
func (d *draftRun) fileBody() (string, error) {
	p := d.o.BodyFile
	if !filepath.IsAbs(p) {
		p = filepath.Join(d.o.Cwd, p)
	}
	b, err := readRegular(p, d.set.Draft.MaxBytes)
	if err != nil {
		return "", errorf(ExitError, "draft_invalid", "--body %s: %v (at most egm.draft.max_bytes, a regular file)", d.o.BodyFile, err)
	}
	if _, secret := Redact(string(b)); secret {
		return "", errorf(ExitError, "draft_secret", "--body %s has a secret-like value; nothing was written", d.o.BodyFile)
	}
	body, ok := cleanPayload(b, d.set.Draft.MaxBytes)
	if !ok {
		return "", errorf(ExitError, "draft_invalid", "--body %s is empty, oversized or not UTF-8 once cleaned", d.o.BodyFile)
	}
	if fs := ScanInjection(ParseDoc(body, nil), d.rel); len(fs) > 0 {
		return "", errorf(ExitError, "draft_injection", "the body %s; nothing was written", strings.TrimPrefix(fs[0].Message, "text "))
	}
	return body, nil
}

// exactSources refuses an assembled document whose R7 sources are not
// exactly want, or that cites anything R7 skips (a URL is not a source).
// before is the skip set the starting document already had.
func exactSources(final *SourceSet, want []string, before *SourceSet) error {
	problems := sourceMismatch(final, want)
	var seen []SkippedSource
	if before != nil {
		seen = before.Skipped
	}
	for _, s := range newSkips(seen, final.Skipped) {
		if s.Reason != "url" {
			problems = append(problems, s.Path+" ("+s.Reason+")")
		}
	}
	if final.MaxExcluded && (before == nil || !before.MaxExcluded) {
		problems = append(problems, "a file over a size limit")
	}
	if len(problems) > 0 {
		return errorf(ExitError, "draft_sources", "the draft cites files that are not exactly the accepted sources: %s; nothing was written", strings.Join(problems, ", "))
	}
	return nil
}

// withRequiredSections appends every section the standard requires that the
// body lacks, with a TODO line the required-sections checker will not accept
// as missing but a reviewer will question.
func withRequiredSections(body, docType string) string {
	d := ParseDoc(body, nil)
	var b strings.Builder
	b.WriteString(strings.TrimSpace(body))
	b.WriteString("\n\n")
	for _, pair := range requiredHeadings[structuralStandard(docType)] {
		if !d.HasHeading(pair[0]) && !d.HasHeading(pair[1]) {
			fmt.Fprintf(&b, "%s\n\nTODO\n\n", pair[0])
		}
	}
	return strings.TrimRight(b.String(), "\n")
}

// splitDoc cuts a document into what precedes its first level-2 heading
// (title, status) and its "## Sources" section, both kept as they are.
func splitDoc(text string) (head, sources string) {
	var h, s []string
	inFence, seenH2, inSrc := false, false, false
	for _, l := range strings.Split(strings.ReplaceAll(text, "\r\n", "\n"), "\n") {
		switch {
		case reFenceLine.MatchString(l):
			inFence = !inFence
		case !inFence && reATX.MatchString(l) && headingLevel(l) == 2:
			seenH2 = true
			inSrc = reSourcesTitle.MatchString(strings.TrimSpace(l))
		}
		switch {
		case inSrc:
			s = append(s, l)
		case !seenH2:
			h = append(h, l)
		}
	}
	if head = strings.TrimSpace(strings.Join(h, "\n")); head != "" {
		head += "\n\n"
	}
	return head, strings.TrimSpace(strings.Join(s, "\n"))
}

func nonNil(s []string) []string {
	if s == nil {
		return []string{}
	}
	return s
}

// draftNext is the next step; where the repository keeps a pt-BR mirror the
// reminder names the twin path.
func draftNext(root, rel string) string {
	next := "tb egm review " + rel
	if rest, ok := strings.CutPrefix(rel, "docs/"); ok {
		if fi, err := os.Stat(filepath.Join(root, "docs", "pt-BR")); err == nil && fi.IsDir() && !strings.HasPrefix(rest, "pt-BR/") {
			next += "; this repository also needs the mirror " + path.Join("docs", "pt-BR", rest)
		}
	}
	return next
}
